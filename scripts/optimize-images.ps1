$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$outputDir = Join-Path $projectRoot 'src/assets/optimized'
New-Item -ItemType Directory -Force $outputDir | Out-Null
$sources = @(
  Get-ChildItem -LiteralPath (Join-Path $projectRoot 'src/assets/hero') -Filter '*.png'
  Get-ChildItem -LiteralPath (Join-Path $projectRoot 'src/assets/services') -Filter '*.png'
)
$imports = [System.Collections.Generic.List[string]]::new()
$entries = [System.Collections.Generic.List[string]]::new()
$totalOriginal = 0
$totalOptimized = 0
foreach ($source in $sources) {
  $probe = (& ffprobe -v error -select_streams v:0 -show_entries stream=width,height -of json $source.FullName) | ConvertFrom-Json
  if ($LASTEXITCODE -ne 0) { throw "Cannot inspect $($source.Name)" }
  $imageWidth = $probe.streams[0].width
  $imageHeight = $probe.streams[0].height
  $variants = [System.Collections.Generic.List[string]]::new()
  $sourceTotal = 0
  $key = $source.BaseName.Replace('-', '_')
  foreach ($targetWidth in @(480, 800, 1120, 1600)) {
    if ($targetWidth -gt $imageWidth) { continue }
    $fileName = "$($source.BaseName)-$targetWidth.webp"
    $outputPath = Join-Path $outputDir $fileName
    & ffmpeg -hide_banner -loglevel error -y -i $source.FullName -vf "scale=${targetWidth}:-2:flags=lanczos" -c:v libwebp -quality 82 -compression_level 6 -frames:v 1 $outputPath
    if ($LASTEXITCODE -ne 0) { throw "Cannot encode $fileName" }
    $variable = "$key$targetWidth"
    $imports.Add("import $variable from '../assets/optimized/$fileName'")
    $variants.Add('${' + $variable + "} ${targetWidth}w")
    $sourceTotal += (Get-Item -LiteralPath $outputPath).Length
  }
  $entries.Add("  '$($source.BaseName)': { src: ${key}800, srcSet: " + [char]96 + ($variants -join ', ') + [char]96 + ", width: $imageWidth, height: $imageHeight },")
  $totalOriginal += $source.Length
  $totalOptimized += $sourceTotal
  Write-Output "$($source.Name): $([math]::Round($source.Length / 1KB)) KB -> $([math]::Round($sourceTotal / 1KB)) KB (all sizes)"
}
$manifest = "// Generated by scripts/optimize-images.ps1; originals are preserved." + [Environment]::NewLine + ($imports -join [Environment]::NewLine) + [Environment]::NewLine + [Environment]::NewLine + "export const optimizedImages = {" + [Environment]::NewLine + ($entries -join [Environment]::NewLine) + [Environment]::NewLine + "} as const" + [Environment]::NewLine
Set-Content -LiteralPath (Join-Path $projectRoot 'src/config/images.ts') -Value $manifest -Encoding utf8
Write-Output "Original total: $totalOriginal bytes. All generated variants: $totalOptimized bytes."
